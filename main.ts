// main.ts — Launch Radar: the token launch radar.
//
// Reads the sealed snapshot, scores every pre-token protocol with the
// value model in lib/model.ts, writes the ranked board, the dashboard's
// data and the dossier. Node 22, standard library only, no network.
//
//   node main.ts [--input <snapshot.json>] [--output <dir>]
//   MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json
//
// Defaults are the grading container's: /input/snapshot.json in,
// /output out. The program runs twice and both runs must write the same
// bytes, so nothing here reads the clock or a random source: the snapshot's
// own as_of is the only date in the run.

import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-board.ts';
import { buildBoard, validateSnapshot } from './lib/model.ts';
import type { Scored } from './lib/model.ts';
import { buildFarmSteps } from './lib/farm.js';
import { checkOutput } from './lib/gate.ts';

const REPO_ROOT = dirname(fileURLToPath(import.meta.url));

/** The dashboard's data file must leave room for the page itself. */
const DATA_BUDGET_BYTES = 30000;

function parseArgs(argv: string[]): { input: string; output: string } {
  let input = '/input/snapshot.json';
  let output =
    process.env.MAKEFUN_OUTPUT_DIR ?? process.env.MAKEFUN_OUTPUT ?? '/output';
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--input' && argv[i + 1] !== undefined) input = argv[++i] as string;
    else if (argv[i] === '--output' && argv[i + 1] !== undefined)
      output = argv[++i] as string;
    else if (argv[i] === '--help' || argv[i] === '-h') {
      console.log(
        'usage: node main.ts [--input <snapshot.json>] [--output <dir>]\n' +
          '  defaults: /input/snapshot.json in, $MAKEFUN_OUTPUT_DIR or /output out.',
      );
      process.exit(0);
    }
  }
  return { input, output };
}

function copyTree(src: string, dst: string): void {
  mkdirSync(dst, { recursive: true });
  for (const entry of readdirSync(src, { withFileTypes: true })) {
    const from = join(src, entry.name);
    const to = join(dst, entry.name);
    if (entry.isDirectory()) copyTree(from, to);
    else if (entry.isFile()) copyFileSync(from, to);
  }
}

function round3(x: number): number {
  return Math.round(x * 1000) / 1000;
}

/**
 * The dashboard's data as one ES module: a META block (the model, its
 * calibration and the board's counts) and the rows as compact arrays, one
 * row per line, so a dossier cut still shows whole rows. Rows are dropped
 * lowest-ranked first when the file would pass its budget — never a
 * watchlist row — and the drop is reported, not hidden.
 */
function renderData(rows: Scored[], meta: Record<string, unknown>): { text: string; kept: number; dropped: number } {
  const kept = [...rows];
  let dropped = 0;
  const build = (): string => {
    const lines = kept.map((r) =>
      JSON.stringify([
        r.slug,
        r.name,
        r.rank,
        r.implied_value_usd,
        r.tvl_usd,
        r.change_7d,
        r.age_days,
        r.category,
        r.chains,
        round3(r.factors.multiple),
        round3(r.factors.growth),
        round3(r.factors.age),
        round3(r.factors.chains),
        r.watchlist ? 1 : 0,
      ]),
    );
    return (
      `// Launch Radar data — generated by main.ts from the sealed snapshot.\n` +
      `// One row per line: [slug, name, rank, implied_value_usd, tvl_usd,\n` +
      `// change_7d, age_days, category, chains, multiple, growth, age, chains, watchlist]\n` +
      `export const RADAR = ${JSON.stringify({ ...meta, rows: '§ROWS§' })};\n`
    ).replace('"§ROWS§"', `[\n${lines.join(',\n')}\n]`);
  };
  let text = build();
  while (
    Buffer.byteLength(text, 'utf8') > DATA_BUDGET_BYTES &&
    kept.length > 0
  ) {
    const idx = [...kept.keys()].reverse().find((i) => !kept[i]!.watchlist);
    if (idx === undefined) break;
    kept.splice(idx, 1);
    dropped++;
    text = build();
  }
  return { text, kept: kept.length, dropped };
}

function main(): number {
  const { input, output } = parseArgs(process.argv.slice(2));
  const snapshot = validateSnapshot(
    JSON.parse(readFileSync(input, 'utf8')) as unknown,
  );
  const board = buildBoard(snapshot);

  const boardRows = board.rows.map((r) => ({
    slug: r.slug,
    name: r.name,
    rank: r.rank,
    implied_value_usd: r.implied_value_usd,
    farm_steps: buildFarmSteps(r),
    category: r.category,
    chains: r.chains,
    tvl_usd: r.tvl_usd,
    change_7d: r.change_7d,
    age_days: r.age_days,
    multiple: round3(r.factors.multiple),
    growth_factor: round3(r.factors.growth),
    age_factor: round3(r.factors.age),
    chain_factor: round3(r.factors.chains),
    watchlist: r.watchlist,
    token_status: 'no-token-recorded',
  }));

  mkdirSync(output, { recursive: true });
  writeFileSync(
    join(output, 'board.json'),
    JSON.stringify({ meta: board.meta, rows: boardRows }, null, 2) + '\n',
    'utf8',
  );

  const dashOut = join(output, 'dashboard');
  copyTree(join(REPO_ROOT, 'dashboard'), dashOut);
  copyFileSync(join(REPO_ROOT, 'lib', 'farm.js'), join(dashOut, 'farm.js'));
  const meta = {
    as_of: board.meta.as_of,
    floor_usd: board.meta.floor_usd,
    universe: board.meta.universe,
    candidates: board.meta.candidates,
    watchlist_count: board.meta.watchlist_count,
    rows: board.meta.rows,
    total_implied_value_usd: board.meta.total_implied_value_usd,
    calibration: board.meta.calibration,
  };
  const data = renderData(board.rows, meta as unknown as Record<string, unknown>);
  writeFileSync(join(dashOut, 'data.js'), data.text, 'utf8');

  const shotsSrc = join(REPO_ROOT, 'screenshots');
  const shotsOut = join(output, 'screenshots');
  if (existsSync(shotsSrc) && statSync(shotsSrc).isDirectory()) {
    copyTree(shotsSrc, shotsOut);
  } else {
    console.log('note: no screenshots/ in the repository yet; the gate will fail on them');
    mkdirSync(shotsOut, { recursive: true });
  }

  try {
    const dossier = buildDossier(output, { text_max_bytes: 65536 });
    writeFileSync(join(output, 'dossier.json'), dossier);
  } catch (err) {
    console.log(`note: dossier not written: ${(err as Error).message}`);
  }

  const results = checkOutput(output, snapshot);
  let failed = 0;
  for (const r of results) {
    console.log(`${r.pass ? 'pass' : 'FAIL'}  ${r.row}: ${r.detail}`);
    if (!r.pass) failed++;
  }
  const top = board.rows.slice(0, 5);
  console.log(
    `board: ${board.rows.length} rows, ${board.meta.watchlist_count} watchlist, ` +
      `total implied value $${board.meta.total_implied_value_usd.toLocaleString('en-US')}`,
  );
  for (const r of top) {
    console.log(
      `  #${r.rank} ${r.name} — $${r.implied_value_usd.toLocaleString('en-US')} ` +
        `(TVL $${r.tvl_usd.toLocaleString('en-US')}, x${round3(r.factors.multiple)})`,
    );
  }
  if (data.dropped > 0)
    console.log(
      `note: dashboard data trimmed to ${data.kept} rows (${data.dropped} lowest non-watchlist rows dropped for the 64 KB source budget)`,
    );
  if (failed > 0) {
    console.log(`gate: ${failed} row(s) failed`);
    return 1;
  }
  console.log('gate: all rows pass');
  return 0;
}

process.exit(main());
